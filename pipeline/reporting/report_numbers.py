"""Write outputs/REPORT_NUMBERS.md: every number the report needs, read from pipeline outputs (no hand-typed values)."""
import json
from pathlib import Path

import numpy as np
import pandas as pd

from pipeline.common.utils import interim


def _md(df: pd.DataFrame, digits=2) -> str:
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            v = d[c].dropna()
            if len(v) and (v == v.round()).all() and v.abs().max() >= 1:
                d[c] = d[c].map(lambda x: "" if pd.isna(x) else f"{int(x):,}" if abs(x) >= 1000 else str(int(x)))
            else:
                d[c] = d[c].round(digits)
    cols = [str(c) for c in d.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in d.iterrows():
        lines.append("| " + " | ".join("" if (isinstance(v, float) and np.isnan(v)) else str(v) for v in r.values) + " |")
    return "\n".join(lines)


def write_report_numbers(cfg, finals, boards):
    out = Path(cfg["paths"]["out"])
    tabs = out / "tables"
    L = ["# REPORT NUMBERS", "", f"Generated by `python run_all.py` (Stage 15). Reference date {cfg['reference_date']}. "
         "Every number below is read from a pipeline output file.", ""]
    b = pd.read_parquet(interim(cfg, "ball_value"))
    m = pd.read_parquet(interim(cfg, "matches"))
    st = pd.read_parquet(interim(cfg, "balls"))

    # 1. data coverage and cleaning
    L += ["## 1. Data coverage and cleaning checks", ""]
    cov = b.groupby("comp_group").agg(balls=("match_id", "size"), matches=("match_id", "nunique")).reset_index()
    L += [f"- Balls: {len(b):,} in {b.match_id.nunique():,} matches ({m.shape[0]:,} matches in the match table); "
          f"seasons {b.season.min()}-{b.season.max()}; {b.comp_name.nunique()} competitions.",
          f"- Players: {b.striker_id.nunique():,} batters faced a ball, {b.bowler_id.nunique():,} bowlers bowled.", "",
          _md(cov), ""]
    ov = st[st.is_legal].groupby(["match_id", "innings", "overid"]).size()
    lastov = st.groupby(["match_id", "innings"]).overid.transform("max")
    comp = st[st.overid < lastov].groupby(["match_id", "innings", "overid"]).is_legal.sum()
    L += [f"- Completed overs with exactly 6 legal balls: {(comp == 6).mean():.2%} of {len(comp):,}.",
          f"- Result types: {m.result_type.value_counts().to_dict()}; DLS / revised matches: {int(m.is_dls.sum())}.",
          f"- Margin check (reconstructed totals vs official margin): {m.margin_ok.mean():.2%} pass over "
          f"{int(m.margin_ok.notna().sum())} checkable matches.",
          f"- Data-suspect matches excluded from ratings: {m.loc[m.data_suspect, 'match_id'].tolist()}.", ""]

    # 2. WP
    wp = json.load(open(tabs / "wp_metrics.json", encoding="utf-8"))
    L += ["## 2. Win-probability models (out-of-fold, 5 match folds)", "",
          _md(pd.DataFrame([{"model": k_, "AUC": v_["auc"], "Brier": v_["brier"], "log-loss": v_["logloss"],
                             "ECE": v_["ece"], "balls": v_["n_balls"]} for k_, v_ in wp.items() if "auc" in v_]), 4),
          "", f"- WP1 smoothness: p99 change per run {wp['WP1_smoothness']['d1_p99']:.3f}, max {wp['WP1_smoothness']['d1_max']:.3f}, "
          f"jumps >= 0.10: {wp['WP1_smoothness']['n_jumps_010']}.", ""]

    # 3. leverage
    conc = pd.read_csv(tabs / "li_concentration.csv")
    sp = pd.read_csv(tabs / "li_within_bucket_spread.csv")
    L += ["## 3. Leverage (pressure definition)", "", "Share of all |change in win probability| carried by the top-x% LI balls:", "",
          _md(conc[["innings", "n_balls", "top10_share_of_abs_dwp", "top20_share_of_abs_dwp", "top30_share_of_abs_dwp"]], 3), "",
          f"- Within the same innings x phase x wickets bucket, LI still varies: median p90/p10 ratio "
          f"{sp.p90_over_p10.median():.2f} (interquartile range {sp.p90_over_p10.quantile(.25):.2f}-"
          f"{sp.p90_over_p10.quantile(.75):.2f}) across {len(sp)} buckets; in buckets holding >= 10% pressure balls "
          f"{sp[sp.pct_pressure >= 0.10].p90_over_p10.median():.2f}. So phase and wickets alone do not define pressure.",
          ]
    col = b.groupby("flag_collapse").LI.mean()
    L += [f"- Collapse finding: mean LI on collapse balls (>= 2 wickets in the last 18 balls) {col.get(True, np.nan):.2f} vs "
          f"{col.get(False, np.nan):.2f} on other balls; share of collapse balls that are pressure balls "
          f"{b.loc[b.flag_collapse, 'is_pressure'].mean():.1%} (vs 20% overall).", ""]

    # 4. raw SR trap
    trap = pd.read_csv(tabs / "raw_sr_trap.csv")
    a = trap[trap.scope == "all"].set_index("ball_type")
    pt = pd.read_csv(tabs / "raw_pressure_trap_players.csv")
    L += ["## 4. The raw-strike-rate trap", "",
          f"- League: raw SR {a.loc['pressure', 'raw_SR']:.1f} on pressure balls vs {a.loc['normal', 'raw_SR']:.1f} on normal "
          f"balls - but the context expects {a.loc['pressure', 'expected_SR']:.1f} vs {a.loc['normal', 'expected_SR']:.1f}. "
          f"Runs above expected per 100 balls: {a.loc['pressure', 'v_bat_per100']:+.2f} vs {a.loc['normal', 'v_bat_per100']:+.2f}.",
          "", _md(trap[["scope", "ball_type", "balls", "raw_SR", "expected_SR", "dismissal_pct", "expected_dismissal_pct"]], 1), "",
          "- Per player (batters with >= 100 pressure balls): raw pressure SR flatters most / undersells most:", "",
          _md(pd.concat([pt.head(5), pt.tail(5)])[["name", "pressure_balls", "pressure_raw_SR", "pressure_SR_minus_xSR",
                                                     "P_star", "rank_raw_pressure_SR", "rank_P_star"]], 1), ""]

    # 5. k values
    kv = json.load(open(tabs / "eb_k_values.json", encoding="utf-8"))
    kp = json.load(open(tabs / "process_k_values.json", encoding="utf-8"))
    rows = []
    for track, K in (("outcome", kv), ("process", kp)):
        for role in ("bat", "bowl"):
            k = K[role]
            rows.append({"track": track, "role": role, "k_B": k["k_B"], "k_P": k["k_P"],
                         "baseline sd /100 (95% CI)": f"{100 * np.sqrt(k['tau2_B']):.2f} ({100 * np.sqrt(k['tau2_B_ci'][0]):.2f}-{100 * np.sqrt(k['tau2_B_ci'][1]):.2f})",
                         "pressure-gap sd /100 (95% CI)": f"{100 * np.sqrt(k['tau2_D']):.2f} ({100 * np.sqrt(k['tau2_D_ci'][0]):.2f}-{100 * np.sqrt(k['tau2_D_ci'][1]):.2f})"})
    L += ["## 5. Shrinkage (REML) and the clutch question", "", _md(pd.DataFrame(rows), 1), "",
          "- k = effective balls before a player's own record counts as much as the prior. k_P is set from the 95% upper "
          "bound of the pressure-gap spread (the largest clutch effect the data cannot rule out).",
          "- Outcome clutch spread: point estimate ~0, CI includes 0 -> clutch outcomes are not detectable. "
          "Process pressure-gap spread: CI excludes 0.", ""]

    # 6. split-half
    sh = pd.read_csv(tabs / "validation_split_half.csv")
    thr = sh[((sh.role == "bat") & (sh.min_pressure_balls == 100)) | ((sh.role == "bowl") & (sh.min_pressure_balls == 120))]
    piv = thr.pivot(index="metric", columns="role", values="spearman_brown")
    nn = thr.groupby("role").n.max()
    L += ["## 6. Split-half reliability (odd vs even matches, Spearman-Brown)", "",
          f"At the eligibility threshold (batters >= 100 pressure balls, n = {nn['bat']}; bowlers >= 120, n = {nn['bowl']}):", "",
          _md(piv.reset_index(), 2), "", "Full curve: `tables/validation_split_half.csv`, `figures/reliability_curve.png`.", ""]

    # 7. temporal
    tt = pd.read_csv(tabs / "validation_temporal.csv")
    for test in tt.test.unique():
        d = tt[(tt.test == test) & (tt.target == "P_raw_test")]
        L += [f"## 7. Temporal test - {test} (target: raw pressure outcome)", "",
              _md(d[["role", "measure", "n", "rho", "lo", "hi", "rup_minus_this_lo", "rup_minus_this_hi"]], 3), ""]
    L += ["- Reading: every 95% interval includes 0; no measure (ours or traditional) predicts next-season raw pressure "
          "outcomes in this sample. Do not claim RUP beats raw stats.", ""]

    # 8. a, weights, eligibility
    wj = json.load(open(tabs / "rup_weights.json", encoding="utf-8"))
    L += ["## 8. Blend weight a, composite weights, eligibility", ""]
    for role in ("bat", "bowl"):
        s = wj["search"][role]
        L += [f"- {role}: a = {s['a']} (Spearman by a: " + ", ".join(f"{r_['a']}: {r_['rho']:+.2f}" for r_ in s["a_search"]) + ")",
              f"  weights used: {wj['chosen'][role]['weights']} ({s['weights_used']}); best {s['best_weights']} rho "
              f"{s['rho_best']:+.3f} vs default rho {s['rho_default']:+.3f}, CI of difference "
              f"[{s['diff_ci95'][0]:+.3f}, {s['diff_ci95'][1]:+.3f}]; analysis n = {s['analysis_n']}"]
    er = pd.read_csv(tabs / "eligibility_removals.csv")
    L += ["", "Players removed by each eligibility rule:", "", _md(er.groupby(["role", "rule"]).size().rename("removed").reset_index()), ""]
    for role in ("bat", "bowl"):
        g = er[(er.role == role) & er.rule.str.startswith("guard")]
        L += [f"- Guard (P_raw >= 0) removes ({role}): " + ", ".join(g.name.tolist())]
    L += [""]

    # 9. final lists
    L += ["## 9. Final top 10s (consensus across sensitivity variants)", ""]
    for role in ("bat", "bowl"):
        t = finals[role]
        L += [f"### {'Batters' if role == 'bat' else 'Bowlers'}", "",
              _md(t[["rank", "name", "teams", "RUP", "R_P", "P_star", "proc_P_star", "R_B", "D_R", "C", "P_raw",
                     "pressure_balls", "p_top10", "median_rank", "rank_p10", "rank_p90", "median_rank_variants",
                     "fragile", "strongest_type"]], 2), ""]
        fr = t[t.fragile]
        L += [f"- Fragile picks (top 10 by default but outside the top 20 in > 30% of variants): "
              f"{', '.join(fr.name) if len(fr) else 'none'}.", ""]
    cons = pd.read_parquet(interim(cfg, "consensus"))
    var = pd.read_csv(tabs / "sensitivity_variants.csv")
    L += [f"- Variants: {len(var)} ({(var.data == 'IPL').sum()} of them IPL-only, which penalises T20I-heavy players).", ""]

    # 10. what pressure changed
    wc = pd.read_csv(tabs / "what_pressure_changed.csv")
    L += ["## 10. What pressure changed (B-only quality rank vs final rank)", ""]
    for role in ("bat", "bowl"):
        n_ = int(wc[(wc.role == role) & (wc.kind == "summary")].rank_change.iloc[0])
        L += [f"- {role}: {n_} of the final top 10 would NOT be top 10 on baseline quality alone."]
        for kind in ("riser", "faller"):
            d = wc[(wc.role == role) & (wc.kind == kind)].head(5)
            L += [f"  - biggest {kind}s: " + "; ".join(f"{r_['name']} (B rank {r_.B_rank:.0f} -> final "
                                                         f"{'removed by guard' if pd.isna(r_.final_rank) else int(r_.final_rank)})"
                                                         for _, r_ in d.iterrows())]
    L += [""]

    # 11. league process insights
    lr = pd.read_csv(tabs / "process_label_rates.csv")
    dv = lr[lr.family == "deliv_fam"].set_index("label")
    sk = lr[lr.family == "stroke_fam"].set_index("label")
    skill = pd.read_csv(tabs / "process_model_skill.csv")
    pv = pd.read_parquet(interim(cfg, "process_value"))
    bb = pd.concat([b[["is_pressure", "pace_or_spin", "is_faced", "phase"]], pv[["deliv_fam", "is_aerial", "is_full_toss",
                                                                              "is_yorker", "is_pace_off", "is_wide_nb"]]], axis=1)
    pace = bb[bb.pace_or_spin == "Pace"]
    mix = pace.groupby("is_pressure")[["is_yorker", "is_full_toss", "is_pace_off", "is_wide_nb"]].mean() * 100
    aer = bb[bb.is_faced].groupby("is_pressure").is_aerial.mean() * 100
    L += ["## 11. League process insights", "",
          f"- Death overs: yorker {dv.loc['Yorker', 'bowler_conceded_pb']:.2f} runs/ball (wicket {dv.loc['Yorker', 'wicket_pct']:.1f}%), "
          f"wide yorker {dv.loc['Wide Yorker', 'bowler_conceded_pb']:.2f}, bouncer {dv.loc['Bouncer', 'bowler_conceded_pb']:.2f}, "
          f"pace-off {dv.loc['pace_off', 'bowler_conceded_pb']:.2f}, seam/swing {dv.loc['seam_swing', 'bowler_conceded_pb']:.2f}, "
          f"full toss {dv.loc['Full Toss', 'bowler_conceded_pb']:.2f}.",
          f"- Strokes: aerial dismissal {sk.loc['aerial', 'dismissal_pct']:.1f}% per ball ({sk.loc['aerial', 'runs_per_ball']:.2f} runs/ball) "
          f"vs rotation {sk.loc['rotation', 'dismissal_pct']:.1f}% ({sk.loc['rotation', 'runs_per_ball']:.2f}), drives "
          f"{sk.loc['drives', 'dismissal_pct']:.1f}%, defence {sk.loc['defence', 'dismissal_pct']:.1f}%.",
          f"- Pace bowlers under pressure vs normal: yorker {mix.loc[True, 'is_yorker']:.1f}% vs {mix.loc[False, 'is_yorker']:.1f}%, "
          f"full toss {mix.loc[True, 'is_full_toss']:.1f}% vs {mix.loc[False, 'is_full_toss']:.1f}%, pace-off "
          f"{mix.loc[True, 'is_pace_off']:.1f}% vs {mix.loc[False, 'is_pace_off']:.1f}%, wide + no-ball "
          f"{mix.loc[True, 'is_wide_nb']:.1f}% vs {mix.loc[False, 'is_wide_nb']:.1f}%.",
          f"- Batters' aerial-shot rate: {aer.loc[True]:.1f}% of pressure balls vs {aer.loc[False]:.1f}% of normal balls.",
          "- Skill added by labels (OOF): " + "; ".join(f"{r_.comparison} {r_.improvement:+.1%}" for r_ in skill.itertuples()), ""]
    ot = pd.read_csv(tabs / "li_outcome_rates.csv")
    cd = ot[(ot.innings == 2) & (ot.phase == "death")]
    L += ["Chase death overs, pressure vs other balls (same wickets bucket):", "",
          _md(cd[["wkt_bucket", "n_pressure", "n_other", "dismissal_pressure", "dismissal_other", "boundary_pressure",
                  "boundary_other", "rpb_pressure", "rpb_other"]], 3), ""]

    # 12. limitations
    L += ["## 12. Limitations", "",
          "1. Clutch (pressure outcome relative to own baseline) is not detectable: outcome pressure gap CI includes 0 and "
          "split-half reliability of raw pressure outcomes is ~0. Rankings mostly reflect pressure-ball quality, shrunk.",
          "2. Temporal validation has low power (one test season, ~20 players); no measure, ours or traditional, "
          "significantly predicts next-season raw pressure outcomes.",
          "3. The blend weight a was chosen on the same small test (a = 0.1 bat, 0.0 bowl); process ratings repeat far "
          "better but enter the final score only weakly.",
          "4. Stroke labels are recorded after the ball by scorers: some outcome information leaks into shot labels; label "
          "coding drifts across seasons (fine-label variant in Stage 12).",
          "5. bowl_exec uses a bowler-type baseline (deviation from the brief, logged); the literal formula is a Stage 12 variant.",
          "6. Outcome ratings are not adjusted for bowler type / matchups; spinners' outcome value partly reflects role.",
          "7. Over-16 leverage step in innings 1; flat early-innings WP1; WP timeline jump at the innings break (mean 0.044); "
          "individual WP2 tree-state errors (e.g. 8 off 4 = 0.857).",
          "8. Extras reconstruction (wides / no-balls / 'other' treated as illegal) and one ambiguous super-over tie (18532).",
          "9. Context models (WP, expectation, process) were fitted out-of-fold on all seasons, so the train-period ratings "
          "in the temporal test use league context that has seen 2026 matches (mild; not player-level).",
          "10. Consistency C for bowlers is near noise (pool spread ~ its bootstrap SE); its weight is fixed at the 0.15 floor.",
          f"11. {(var.data == 'IPL').sum()} of {len(var)} sensitivity variants are IPL-only (random draw), which penalises T20I-heavy players in the consensus.",
          "12. Survivorship: only players who received pressure chances can qualify; no venue names; no SMAT / domestic data; "
          "availability and age unknown (external files missing).", ""]
    (out / "REPORT_NUMBERS.md").write_text("\n".join(L), encoding="utf-8")
    print(f"  wrote {out / 'REPORT_NUMBERS.md'} ({len(L)} lines)")
